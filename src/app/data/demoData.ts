/**
 * Get demo category by ID
 */
export function getDemoCategoryById(id: string): CategoryEntity | undefined {
  return demoCategories.find(cat => cat.id === id);
}

/**
 * Get demo transactions with computed category info
 */
export function getDemoTransactionsWithCategories(): CashFlowEntity[] {
  return demoTransactions.map(tx => {
    const category = getDemoCategoryById(tx.categoryId);
    return {
      ...tx,
      categoryName: category?.name || 'Unknown',
      categoryType: category?.type || 'expense',
    };
  });
}

/**
 * Get demo income total
 */
export function getDemoIncomeTotal(): number {
  return demoTransactions
    .filter(tx => {
      const cat = getDemoCategoryById(tx.categoryId);
      return cat?.type === 'income';
    })
    .reduce((sum, tx) => sum + tx.amount, 0);
}

/**
 * Get demo expense total
 */
export function getDemoExpenseTotal(): number {
  return demoTransactions
    .filter(tx => {
      const cat = getDemoCategoryById(tx.categoryId);
      return cat?.type === 'expense';
    })
    .reduce((sum, tx) => sum + tx.amount, 0);
}

/**
 * Get demo balance
 */
export function getDemoBalance(): number {
  return getDemoIncomeTotal() - getDemoExpenseTotal();
}